// Generates lib/postcode-districts.ts: one point (latitude, longitude) inside each Scottish postcode
// district, so the portfolio map can place a property by the district of its postcode without sending
// the address anywhere. Source: missinglink/uk-postcode-polygons (derived from Ordnance Survey and
// Open Data; district outlines only, no addresses). Run it from anywhere:
//   mkdir /tmp/pc && cd /tmp/pc && for a in AB DD DG EH FK G HS IV KA KW KY ML PA PH TD ZE; do
//     curl -sSO https://raw.githubusercontent.com/missinglink/uk-postcode-polygons/master/geojson/$a.geojson; done
//   node scripts/build-postcode-districts.mjs /tmp/pc lib/postcode-districts.ts
import fs from 'node:fs';
import { BOUNDS, projectXY, unprojectXY } from '../lib/scotland-projection.ts';
import { COUNCIL_AREAS } from '../lib/scotland-geo.ts';

const [dir, out] = process.argv.slice(2);
const inside = (ring, x, y) => { let c = false; for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) { const [xi, yi] = ring[i], [xj, yj] = ring[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; };
const edge = (ring, x, y) => { let best = Infinity; for (let i = 0; i < ring.length; i++) { const [ax, ay] = ring[i], [bx, by] = ring[(i + 1) % ring.length], dx = bx - ax, dy = by - ay, t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy || 1))); best = Math.min(best, Math.hypot(x - ax - t * dx, y - ay - t * dy)); } return best; };
const area = ring => Math.abs(ring.reduce((s, [x, y], i) => { const [x2, y2] = ring[(i + 1) % ring.length]; return s + x * y2 - x2 * y; }, 0) / 2);
function pole(ring) {
  let box = [Math.min(...ring.map(p => p[0])), Math.min(...ring.map(p => p[1])), Math.max(...ring.map(p => p[0])), Math.max(...ring.map(p => p[1]))], best = { x: ring[0][0], y: ring[0][1], d: -1 };
  for (let pass = 0; pass < 3; pass++) {
    const w = box[2] - box[0], h = box[3] - box[1];
    for (let i = 0; i <= 20; i++) for (let j = 0; j <= 20; j++) { const x = box[0] + (w * i) / 20, y = box[1] + (h * j) / 20; if (!inside(ring, x, y)) continue; const d = edge(ring, x, y); if (d > best.d) best = { x, y, d }; }
    box = [best.x - w / 20, best.y - h / 20, best.x + w / 20, best.y + h / 20];
  }
  return best;
}
// The map's land is drawn from simplified outlines, so a point on a coastal district (Leith, say) can
// fall a hair into the sea. Such points are moved to the nearest bit of drawn land.
const drawn = COUNCIL_AREAS.flatMap(a => a.d.split('M').filter(Boolean).map(part => {
  const [start, rest = ''] = part.split(/[lL]/), nums = t => t.replace(/z/gi, '').trim().split(/[\s,]+/).filter(Boolean).map(Number);
  const [x0, y0] = nums(start); const pts = [[x0, y0]]; let x = x0, y = y0; const steps = nums(rest);
  for (let i = 0; i + 1 < steps.length; i += 2) { x += steps[i]; y += steps[i + 1]; pts.push([x, y]); }
  return pts;
}));
// A point counts as land only with a little room round it, so rounding cannot tip it into the sea.
const land = (x, y) => drawn.some(r => inside(r, x, y));
const onLand = (x, y) => land(x, y) && [[0.5, 0], [-0.5, 0], [0, 0.5], [0, -0.5]].every(([dx, dy]) => land(x + dx, y + dy));
function snap(lon, lat) {
  const [px, py] = projectXY(lon, lat);
  if (onLand(px, py)) return [lon, lat];
  for (let r = 0.1; r <= 8; r += 0.1) for (let a = 0; a < 24; a++) { const x = px + r * Math.cos((a * Math.PI) / 12), y = py + r * Math.sin((a * Math.PI) / 12); if (onLand(x, y)) return unprojectXY(x, y); }
  return [lon, lat];
}
const table = {};
for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.geojson')).sort()) {
  for (const f of JSON.parse(fs.readFileSync(`${dir}/${file}`, 'utf8')).features) {
    const parts = f.geometry.type === 'GeometryCollection' ? f.geometry.geometries : [f.geometry];
    const polys = parts.flatMap(g => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []));
    if (!polys.length) continue;
    const biggest = polys.map(p => p[0]).reduce((m, r) => (area(r) > area(m) ? r : m));
    const spot = pole(biggest), [x, y] = snap(spot.x, spot.y);
    if (x < BOUNDS.lonMin || x > BOUNDS.lonMax || y < BOUNDS.latMin || y > BOUNDS.latMax) continue;
    table[f.properties.name] = [Math.round(y * 1000) / 1000, Math.round(x * 1000) / 1000];
  }
}
const rows = Object.keys(table).sort((a, b) => a.localeCompare(b, 'en', { numeric: true })).map(k => `  ${JSON.stringify(k)}: [${table[k][0]}, ${table[k][1]}],`);
fs.writeFileSync(out, `// Generated by scripts/build-postcode-districts.mjs. Do not edit by hand.
// A point inside each Scottish postcode district: [latitude, longitude].
export const POSTCODE_DISTRICTS: Record<string, readonly [number, number]> = {
${rows.join('\n')}
};
`);
